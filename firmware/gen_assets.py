# PlatformIO pre-build script: turns web/* into src/web_assets.c (gzip-compressed C arrays).
import gzip, os
Import("env")  # noqa: F821  (provided by PlatformIO)

root = env.subst("$PROJECT_DIR")  # noqa: F821
files = ["index.html", "app.js", "style.css", "setup.html"]
out = ["/* generated by gen_assets.py - do not edit */", '#include "web_assets.h"']
for name in files:
    data = gzip.compress(open(os.path.join(root, "web", name), "rb").read(), 9, mtime=0)
    sym = name.replace(".", "_")
    out.append(f"const unsigned char asset_{sym}[] = {{")
    for i in range(0, len(data), 24):
        out.append(",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"const unsigned int asset_{sym}_len = {len(data)};")
new = "\n".join(out) + "\n"
path = os.path.join(root, "src", "web_assets.c")
if not os.path.exists(path) or open(path).read() != new:
    open(path, "w").write(new)
